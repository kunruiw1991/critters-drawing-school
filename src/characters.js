// 8 Official Smiling Critters Step-by-Step Line-Art Drawing & 7-Part Guided Coloring Lessons!
// Canvas coordinate system: 800 x 640.
// Traced strokes and enclosed coloring regions are extracted from assets/lineart/*_line_art.png
// via tools/extract_lineart.py into ./lineart_data.js.

import { LINEART_DATA } from './lineart_data.js';

function makeCritterLesson(spec) {
  const art = LINEART_DATA[spec.id];
  if (!art) {
    throw new Error(`Missing LINEART_DATA for critter "${spec.id}"`);
  }

  const drawSteps = [
    {
      stepNum: 1,
      id: 'draw_head',
      title: 'Step 1: Head & Cheeks',
      hint: `Start at the green dot and trace ${spec.name}'s head outline!`,
      voiceId: 'draw_step_1',
      strokes: art.stepStrokes[0],
    },
    {
      stepNum: 2,
      id: 'draw_ears',
      title: `Step 2: ${spec.earLabel}`,
      hint: `Trace ${spec.name}'s cute ${spec.earLabel.toLowerCase()} on top!`,
      voiceId: 'draw_step_2',
      strokes: art.stepStrokes[1],
    },
    {
      stepNum: 3,
      id: 'draw_eyes_nose',
      title: `Step 3: Big Eyes & ${spec.noseLabel}`,
      hint: `Draw the big expressive eyes and ${spec.noseLabel.toLowerCase()}!`,
      voiceId: 'draw_step_3',
      strokes: art.stepStrokes[2],
    },
    {
      stepNum: 4,
      id: 'draw_smile',
      title: 'Step 4: Big Smiling Critter Grin!',
      hint: 'Trace the giant happy smile and cute tongue!',
      voiceId: 'draw_step_4',
      strokes: art.stepStrokes[3],
    },
    {
      stepNum: 5,
      id: 'draw_body_limbs',
      title: 'Step 5: Cozy Body, Arms & Paws',
      hint: `Draw ${spec.name}'s tummy, arms, hands, and feet!`,
      voiceId: 'draw_step_5',
      strokes: art.stepStrokes[4],
    },
    {
      stepNum: 6,
      id: 'draw_pendant_tail',
      title: `Step 6: ${spec.pendantLabel} & Tail`,
      hint: `Finish with the ${spec.pendantLabel.toLowerCase()} and ${spec.tailLabel.toLowerCase()}!`,
      voiceId: 'draw_step_6',
      strokes: art.stepStrokes[5],
    },
  ];

  const colorSteps = [
    {
      stepNum: 1,
      partId: 'main_fur',
      title: `Color Step 1/7: ${spec.mainPartTitle}`,
      hint: `Pick ${spec.baseColorName} and brush inside ${spec.name}'s main coat!`,
      voiceId: 'color_step_1',
      recommendedColor: spec.palette.base,
      defaultTool: 'crayon',
      targetCenter: art.targets.main_fur,
    },
    {
      stepNum: 2,
      partId: 'inner_ears_muzzle',
      title: `Color Step 2/7: ${spec.innerPartTitle}`,
      hint: `Switch to ${spec.innerColorName} to color inside the lines!`,
      voiceId: 'color_step_2',
      recommendedColor: spec.palette.inner,
      defaultTool: 'marker',
      targetCenter: art.targets.inner_ears_muzzle,
    },
    {
      stepNum: 3,
      partId: 'tummy_collar',
      title: `Color Step 3/7: ${spec.bellyPartTitle}`,
      hint: `Use ${spec.bellyColorName} to fill the cozy tummy, paws & collar!`,
      voiceId: 'color_step_3',
      recommendedColor: spec.palette.belly,
      defaultTool: 'crayon',
      targetCenter: art.targets.tummy_collar,
    },
    {
      stepNum: 4,
      partId: 'cheeks_mouth',
      title: `Color Step 4/7: ${spec.mouthPartTitle}`,
      hint: `Brush ${spec.cheekColorName} onto the happy tongue & cute details!`,
      voiceId: 'color_step_4',
      recommendedColor: spec.palette.cheek,
      defaultTool: 'watercolor',
      targetCenter: art.targets.cheeks_mouth,
    },
    {
      stepNum: 5,
      partId: 'magic_pendant',
      title: `Color Step 5/7: ${spec.pendantLabel}`,
      hint: `Use sparkling ${spec.pendantColorName} to make the ${spec.pendantLabel.toLowerCase()} shine!`,
      voiceId: 'color_step_5',
      recommendedColor: spec.palette.pendant,
      defaultTool: 'glitter',
      targetCenter: art.targets.magic_pendant,
    },
    {
      stepNum: 6,
      partId: 'shading_sparkles',
      title: 'Color Step 6/7: Velvet Smile & Eye Sparkles',
      hint: 'Fill the big pupils and wide smile with Velvet Ink to make the eyes sparkle!',
      voiceId: 'color_step_6',
      recommendedColor: spec.palette.shade,
      defaultTool: 'marker',
      targetCenter: art.targets.shading_sparkles,
    },
    {
      stepNum: 7,
      partId: 'background_frame',
      title: 'Color Step 7/7: Sunny Sky Background & Stickers',
      hint: 'Color the sky around your friend and add magic sparkles!',
      voiceId: 'color_step_7',
      recommendedColor: spec.palette.bg,
      defaultTool: 'glitter',
      targetCenter: art.targets.background_frame,
    },
  ];

  return {
    ...spec,
    lineArt: `assets/lineart/${spec.stem}_line_art.png`,
    thumb: `assets/thumbs/${spec.stem}.png`,
    strokeWidth: art.strokeWidth,
    regions: art.regions,
    targets: art.targets,
    eyeWhites: art.eyeWhites,
    catchlights: art.catchlights,
    drawSteps,
    colorSteps,
  };
}

